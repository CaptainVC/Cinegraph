REVIEW_PRIMARY_RESULT_PROCESSING_WORKER_GID: Final = GID_IN_CONTAINER

# Keep the sudo policy byte-for-byte chained from the immediately preceding
# host contract.  Each line grants one exact no-argument helper only.
